// ---------- плеер тура (может быть в модалке или встроен в настройки) ----------

export function TourPlayer({
  tourId,
  onExit,
  onComplete,
  onPractice,
  embedded = false,
}: {
  tourId: TourId;
  onExit: () => void;
  onComplete?: (id: TourId) => void;
  /** запустить практический урок этого тура поверх редактора (необязательно) */
  onPractice?: (id: PracticeId) => void;
  embedded?: boolean;
}) {
  const tour = TOURS.find((t) => t.id === tourId)!;
  const practiceId = PRACTICE_OF[tourId];
  const practice = practiceId ? practiceById(practiceId) : null;
  const [step, setStep] = useState(0);
  const highlightRef = useRef<HTMLElement | null>(null);

  const goNext = useCallback(() => {
    if (step < tour.steps.length - 1) setStep(step + 1);
    else {
      onComplete?.(tour.id);
      onExit();
    }
  }, [step, tour, onComplete, onExit]);

  const goPrev = useCallback(() => { if (step > 0) setStep(step - 1); }, [step]);
  const skip = useCallback(() => onExit(), [onExit]);

  useEffect(() => {
    if (highlightRef.current) { highlightRef.current.classList.remove('tour-highlight'); highlightRef.current = null; }
    const s = tour.steps[step];
    if (s.highlight) {
      const el = document.querySelector(s.highlight) as HTMLElement | null;
      if (el) { el.classList.add('tour-highlight'); highlightRef.current = el; }
    }
    return () => { if (highlightRef.current) { highlightRef.current.classList.remove('tour-highlight'); highlightRef.current = null; } };
  }, [tour, step]);

  useEffect(() => {
    const h = (e: KeyboardEvent) => {
      if (e.key === 'ArrowRight' || e.key === 'Enter') { e.preventDefault(); goNext(); }
      else if (e.key === 'ArrowLeft') { e.preventDefault(); goPrev(); }
      else if (e.key === 'Escape') { e.preventDefault(); skip(); }
    };
    window.addEventListener('keydown', h);
    return () => window.removeEventListener('keydown', h);
  }, [goNext, goPrev, skip]);

  const cur = tour.steps[step];
  const pct = ((step + 1) / tour.steps.length) * 100;

  const inner = (
    <>
      <div className="tour-progress"><div className="tour-progress-bar" style={{ width: `${pct}%` }} /></div>
      <div className="tour-step-header">
        <span className="tour-emoji">{tour.emoji}</span>
        <div>
          <h3>{cur.title}</h3>
          <small>{tour.title} — шаг {step + 1} из {tour.steps.length}</small>
        </div>
        <LevelBadge level={tour.level} />
      </div>

      <div className="tour-step-layout">
        <div className="tour-step-main">
          <div className="tour-step-text">{cur.text}</div>
          {cur.tip && <div className="tour-tip"><b>💡 Совет:</b> {cur.tip}</div>}
          {cur.warning && <div className="tour-warn"><b>⚠️ Внимание:</b> {cur.warning}</div>}
          {cur.kbd && cur.kbd.length > 0 && (
            <div className="tour-kbd-row">Горячие клавиши: {cur.kbd.map((k) => <span key={k} className="kbd">{k}</span>)} </div>
          )}
        </div>
        {cur.demo && <div className="tour-step-demo">{cur.demo}</div>}
      </div>

      <div className="tour-dots">
        {tour.steps.map((_, i) => (
          <button key={i} className={'tour-dot' + (i === step ? ' active' : '') + (i < step ? ' passed' : '')} onClick={() => setStep(i)} title={`Шаг ${i + 1}: ${tour.steps[i].title}`} />
        ))}
      </div>

      <div className="tour-footer">
        <button className="btn" onClick={skip} title="Закрыть тур — обучение добровольное">Выйти</button>
        <div className="tour-nav">
          {practice && onPractice && (
            <button
              className="btn tour-practice-btn"
              onClick={() => { onComplete?.(tour.id); onPractice(practice.id); }}
              title={`Не читать, а сделать: ${practice.title} — подсветка на интерфейсе, ${practice.steps.length} шага`}
            >
              {practice.emoji} Практика ▶
            </button>
          )}
          <button className="btn" onClick={goPrev} disabled={step === 0}>← Назад</button>
          <button className="btn primary" onClick={goNext}>{step < tour.steps.length - 1 ? 'Далее →' : 'Завершить ✓'}</button>
        </div>
      </div>
    </>
  );

  if (embedded) return <div className="tour-embedded">{inner}</div>;

  return (
    <Modal title={`${tour.emoji} ${tour.title}`} className="tour-modal tour-active-modal" onClose={onExit} foot={null}>
      {inner}
    </Modal>
  );
}

